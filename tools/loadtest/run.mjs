// StartupTN HR load test: N temporary test staff check in within S seconds (real app path: home load,
// server warm-up, one-request selfie check-in, timing report), then all check out in a short burst.
// Creates temporary accounts (marked test, left out of HR/Chairman numbers) and deletes everything afterwards.
// Run only from GitHub Actions (.github/workflows/loadtest.yml); keys come from Supabase via the access token.
import { readFileSync, writeFileSync, appendFileSync } from 'node:fs';

const { SUPA_URL, ANON, SERVICE, REF, SUPABASE_ACCESS_TOKEN, N = '120', SECONDS = '60', BURST = '10' } = process.env;
const n = Number(N), secs = Number(SECONDS), burst = Number(BURST);
const selfie = readFileSync(new URL('./selfie.jpg', import.meta.url));
const email = (i) => `naveenflop+lt${String(i).padStart(3, '0')}@gmail.com`;   // valid inbox domain; no mail is ever sent
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const svc = { apikey: SERVICE, Authorization: `Bearer ${SERVICE}` };
const log = (...a) => console.log(new Date().toISOString().slice(11, 19), ...a);

async function rest(path, init = {}) {
  const r = await fetch(`${SUPA_URL}${path}`, { ...init, headers: { ...svc, 'Content-Type': 'application/json', ...(init.headers ?? {}) } });
  const t = await r.text();
  if (!r.ok) throw new Error(`${init.method ?? 'GET'} ${path.split('?')[0]} ${r.status} ${t.slice(0, 200)}`);
  return t ? JSON.parse(t) : null;
}
const mgmt = (path, init = {}) => fetch(`https://api.supabase.com/v1/projects/${REF}${path}`, { ...init, headers: { Authorization: `Bearer ${SUPABASE_ACCESS_TOKEN}`, 'Content-Type': 'application/json', ...(init.headers ?? {}) } });
const pct = (a, p) => { if (!a.length) return null; const s = [...a].sort((x, y) => x - y); return s[Math.min(s.length - 1, Math.floor(s.length * p))]; };
const stats = (a) => ({ n: a.length, p50: pct(a, 0.5), p90: pct(a, 0.9), p95: pct(a, 0.95), max: a.length ? Math.max(...a) : null });

const users = [];        // { i, email, id, token }
let savedLimits = null;

async function setup() {
  // 1. auth verify rate limit: raise for the test (restored at the end)
  try {
    const r = await mgmt('/config/auth');
    if (r.ok) {
      const c = await r.json();
      savedLimits = { rate_limit_verify: c.rate_limit_verify };
      const p = await mgmt('/config/auth', { method: 'PATCH', body: JSON.stringify({ rate_limit_verify: Math.max(1000, c.rate_limit_verify ?? 0) }) });
      log('auth verify limit', savedLimits.rate_limit_verify, '->', p.ok ? 'raised for the test' : `not changed (${p.status})`);
    } else log('auth config not readable', r.status, '(will pace sign-ins)');
  } catch (e) { log('auth config error', String(e).slice(0, 120)); }

  const [hub] = await rest('/rest/v1/hubs?name=eq.Chennai&select=id,lat,lng,radius_m');
  if (!hub) throw new Error('Chennai hub not found');
  // 2. roster rows (test accounts), 3. accounts, consent
  const rows = Array.from({ length: n }, (_, k) => ({ email: email(k + 1), full_name: `Load test ${String(k + 1).padStart(3, '0')}`, role: 'staff', hub_name: 'Chennai', designation: 'Load test', is_test: true, test_mode: true }));
  await rest('/rest/v1/staff_roster?on_conflict=email', { method: 'POST', headers: { Prefer: 'resolution=merge-duplicates' }, body: JSON.stringify(rows) });
  for (let k = 0; k < n; k++) {
    const e = email(k + 1);
    let id;
    const r = await fetch(`${SUPA_URL}/auth/v1/admin/users`, { method: 'POST', headers: { ...svc, 'Content-Type': 'application/json' }, body: JSON.stringify({ email: e, email_confirm: true }) });
    const j = await r.json();
    if (r.ok) id = j.id;
    else {   // left over from an earlier run
      const list = await rest(`/auth/v1/admin/users?per_page=1000`);
      id = (list.users ?? []).find((u) => u.email === e)?.id;
      if (!id) throw new Error(`create user ${e}: ${r.status} ${JSON.stringify(j).slice(0, 160)}`);
    }
    users.push({ i: k + 1, email: e, id });
  }
  await rest(`/rest/v1/profiles?id=in.(${users.map((u) => u.id).join(',')})`, { method: 'PATCH', body: JSON.stringify({ consent_at: new Date().toISOString() }) });
  log(`created ${users.length} test accounts`);
  // 4. sessions: magic link generated by the server (no email sent), verified to get a sign-in token
  for (const u of users) {
    for (let attempt = 0; attempt < 20; attempt++) {
      const g = await fetch(`${SUPA_URL}/auth/v1/admin/generate_link`, { method: 'POST', headers: { ...svc, 'Content-Type': 'application/json' }, body: JSON.stringify({ type: 'magiclink', email: u.email }) });
      const gj = await g.json();
      const hashed = gj.hashed_token ?? gj.properties?.hashed_token;
      const v = await fetch(`${SUPA_URL}/auth/v1/verify`, { method: 'POST', headers: { apikey: ANON, 'Content-Type': 'application/json' }, body: JSON.stringify({ type: 'magiclink', token_hash: hashed }) });
      const vj = await v.json();
      if (v.ok && vj.access_token) { u.token = vj.access_token; break; }
      if (v.status === 429) { log('sign-in rate limited, waiting'); await sleep(20000); continue; }
      throw new Error(`verify ${u.email}: ${v.status} ${JSON.stringify(vj).slice(0, 160)}`);
    }
  }
  log(`signed in ${users.filter((u) => u.token).length} accounts`);
  return hub;
}

async function call(u, body, isForm = false) {
  const t0 = performance.now();
  const r = await fetch(`${SUPA_URL}/functions/v1/check-in`, { method: 'POST', headers: { apikey: ANON, Authorization: `Bearer ${u.token}`, ...(isForm ? {} : { 'Content-Type': 'application/json' }) }, body: isForm ? body : JSON.stringify(body) });
  const j = await r.json().catch(() => ({}));
  return { ms: Math.round(performance.now() - t0), ok: r.ok, status: r.status, error: j.error, j };
}

async function oneUser(u, hub, kind, warm) {
  const res = { home: null, ping: null, punch: null, error: null };
  try {
    if (warm) {
      const t0 = performance.now();
      const h = await fetch(`${SUPA_URL}/rest/v1/rpc/my_today`, { method: 'POST', headers: { apikey: ANON, Authorization: `Bearer ${u.token}`, 'Content-Type': 'application/json' }, body: '{}' });
      res.home = Math.round(performance.now() - t0); if (!h.ok) res.error = `home ${h.status}`;
      res.ping = (await call(u, { action: 'ping' })).ms;
      await sleep(3000);   // camera, face guide, countdown
    }
    const spots = [[0, 0], [0.0001, 0.00008], [-0.00009, 0.00011], [0.00012, -0.0001], [-0.0001, -0.00007]];
    const [dl, dg] = spots[u.i % spots.length];
    const key = crypto.randomUUID();
    const fd = new FormData();
    fd.append('data', JSON.stringify({ kind, idempotency_key: key, device_key: `loadtest-${u.i}`, platform: 'web', client_time: new Date().toISOString(),
      location: { lat: hub.lat + dl, lng: hub.lng + dg, accuracy: 12, altitude: null, speed: null, mocked: null }, liveness: { challenge: 'blink', passed: true }, timings: { before_send_ms: 0 } }));
    fd.append('selfie', new Blob([selfie], { type: 'image/jpeg' }), 'selfie.jpg');
    const p = await call(u, fd, true);
    res.punch = p.ms;
    if (!p.ok) res.error = `${kind} ${p.status} ${p.error ?? ''}`;
    else void call(u, { action: 'timing', idempotency_key: key, total_ms: p.ms }).catch(() => undefined);
  } catch (e) { res.error = String(e).slice(0, 120); }
  return res;
}

async function phase(name, hub, kind, windowSec, warm) {
  log(`${name}: ${users.length} ${kind} over ${windowSec}s`);
  const t0 = Date.now();
  const all = await Promise.all(users.map((u, k) => sleep((k * windowSec * 1000) / users.length).then(() => oneUser(u, hub, kind, warm))));
  const wall = Math.round((Date.now() - t0) / 1000);
  const errs = all.filter((r) => r.error).map((r) => r.error);
  return { name, kind, windowSec, wallSec: wall, punch: stats(all.map((r) => r.punch).filter((x) => x != null)), home: stats(all.map((r) => r.home).filter((x) => x != null)),
    ping: stats(all.map((r) => r.ping).filter((x) => x != null)), errors: errs.length, errorSamples: [...new Set(errs)].slice(0, 6) };
}

async function cleanup() {
  const ids = users.map((u) => u.id).filter(Boolean);
  if (ids.length) {
    const inList = `(${ids.join(',')})`;
    try {
      const pun = await rest(`/rest/v1/punches?user_id=in.${inList}&select=selfie_key`);
      const keys = pun.map((p) => p.selfie_key).filter(Boolean).map((k) => k.replace(/^selfies\//, ''));
      for (let i = 0; i < keys.length; i += 100) await fetch(`${SUPA_URL}/storage/v1/object/selfies`, { method: 'DELETE', headers: { ...svc, 'Content-Type': 'application/json' }, body: JSON.stringify({ prefixes: keys.slice(i, i + 100) }) });
      log(`removed ${keys.length} test photos`);
    } catch (e) { log('photo cleanup', String(e).slice(0, 160)); }
    for (const t of ['flags', 'attendance_days', 'punches', 'notifications', 'devices']) {
      try { await rest(`/rest/v1/${t}?user_id=in.${inList}`, { method: 'DELETE' }); } catch (e) { log(`cleanup ${t}`, String(e).slice(0, 160)); }
    }
    try { await rest(`/rest/v1/notifications?kind=eq.slow_checkin&body=like.Load%20test*`, { method: 'DELETE' }); } catch (e) { log('cleanup alerts', String(e).slice(0, 160)); }
    let gone = 0;
    for (const id of ids) { const r = await fetch(`${SUPA_URL}/auth/v1/admin/users/${id}`, { method: 'DELETE', headers: svc }).catch(() => null); if (r?.ok) gone++; }
    log(`deleted ${gone}/${ids.length} test accounts`);
    if (false) for (const id of ids) await fetch(`${SUPA_URL}/auth/v1/admin/users/${id}`, { method: 'DELETE', headers: svc }).catch(() => undefined);
  }
  // '+' must be encoded (%2B) or the filter reads it as a space and matches nothing
  try {
    const gone = await rest(`/rest/v1/staff_roster?email=like.${encodeURIComponent('naveenflop+lt%')}`, { method: 'DELETE', headers: { Prefer: 'return=representation' } });
    log(`removed ${gone?.length ?? 0} roster rows`);
    const left = await rest(`/rest/v1/staff_roster?select=email&email=like.${encodeURIComponent('naveenflop+lt%')}`);
    if (left.length) throw new Error(`${left.length} roster rows still there`);
  } catch (e) { log('cleanup roster FAILED', String(e).slice(0, 160)); process.exitCode = 1; }
  if (savedLimits?.rate_limit_verify != null) {
    const r = await mgmt('/config/auth', { method: 'PATCH', body: JSON.stringify(savedLimits) });
    log('auth verify limit restored', r.ok ? savedLimits.rate_limit_verify : `FAILED ${r.status}`);
  }
  log('cleanup done');
}

const fmt = (s) => (s.n ? `${(s.p50 / 1000).toFixed(2)} s / ${(s.p95 / 1000).toFixed(2)} s / ${(s.max / 1000).toFixed(2)} s` : '—');
let report = { ok: false };
try {
  const hub = await setup();
  const a = await phase('Morning check-in', hub, 'in', secs, true);
  await sleep(5000);
  const b = await phase('Burst check-out', hub, 'out', burst, false);
  const server = await rest(`/rest/v1/punches?user_id=in.(${users.map((u) => u.id).join(',')})&select=kind,timings`);
  const sv = (k) => stats(server.map((x) => x.timings?.[k]).filter((v) => typeof v === 'number'));
  report = { ok: true, users: users.length, phases: [a, b], server: { server_ms: sv('server_ms'), upload_ms: sv('upload_ms'), auth_ms: sv('auth_ms') }, saved: server.length };
} catch (e) { report = { ok: false, error: String(e) }; log('FAILED', String(e)); }
finally { await cleanup(); }

writeFileSync('loadtest-result.json', JSON.stringify(report, null, 2));
let md = `## StartupTN HR load test\n\n`;
if (report.ok) {
  md += `${report.users} test staff · ${report.saved} check-ins/outs saved · all test data deleted afterwards\n\n| Phase | Window | Save time p50 / p95 / max | Home load p50 / p95 | Errors |\n|---|---|---|---|---|\n`;
  for (const p of report.phases) md += `| ${p.name} | ${p.users ?? report.users} in ${p.windowSec}s | ${fmt(p.punch)} | ${p.home.n ? fmt(p.home).split(' / ').slice(0, 2).join(' / ') : '—'} | ${p.errors}${p.errorSamples.length ? ` (${p.errorSamples.join('; ')})` : ''} |\n`;
  md += `\nServer work per save p50/p95: ${fmt(report.server.server_ms)} · photo upload p50/p95: ${fmt(report.server.upload_ms)}\n`;
} else md += `Failed: ${report.error}\n`;
console.log(md);
if (process.env.GITHUB_STEP_SUMMARY) appendFileSync(process.env.GITHUB_STEP_SUMMARY, md);
process.exit(report.ok ? 0 : 1);
